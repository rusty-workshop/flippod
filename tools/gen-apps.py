#!/usr/bin/env python3
"""Generate app/js/apps.js from the apps installed on the phone (via adb root)."""
import json, subprocess, zipfile, io, pathlib

HIDE = {"system", "shared", "keyboard", "ftu", "callscreen", "emergency-call", "network-alerts", "wappush", "stk",
        "loginpages", "logmanager", "mmitest", "engmode", "customization", "antitheft", "launcher", "ringtones",
        "wallpaper", "download", "tctfota", "probe", "flippod", "kaios-pay", "cached", "bluetooth"}
RENAME = {"communications": "Phone", "contact": "Contacts", "sms": "Messages", "fm": "FM Radio",
          "filemanager": "Files", "soundrecorder": "Recorder", "googlesearch": "Search", "music": "KaiOS Music"}

def sh(cmd):
    return subprocess.run(["adb", "shell", cmd], capture_output=True, text=True).stdout

names = sh("ls /data/local/webapps/vroot").split()
apps = []
for n in names:
    if n in HIDE:
        continue
    raw = subprocess.run(["adb", "exec-out", f"cat /data/local/webapps/vroot/{n}/application.zip"], capture_output=True).stdout
    try:
        z = zipfile.ZipFile(io.BytesIO(raw))
        m = json.loads(z.read("manifest.webmanifest"))
        try:
            m.update({k: v for k, v in json.loads(z.read("manifest.en-US.webmanifest")).items() if k in ("name", "short_name")})
        except KeyError:
            pass
    except Exception as e:
        print("skip", n, e)
        continue
    icons = sorted(m.get("icons", []), key=lambda i: abs(int(str(i.get("sizes", "56x56")).split("x")[0]) - 56))
    icon = icons[0]["src"] if icons else ""
    host = f"http://{n}.localhost"
    name = RENAME.get(n, m.get("short_name") or m.get("name") or n)
    apps.append({"name": name, "manifest": f"{host}/manifest.webmanifest", "icon": host + (icon if icon.startswith("/") else "/" + icon) if icon else ""})
apps.sort(key=lambda a: a["name"].lower())
out = pathlib.Path(__file__).resolve().parent.parent / "app/js/apps.js"
out.write_text("// Generated by tools/gen-apps.py from the apps installed on the phone.\nexport const APPS = " + json.dumps(apps, indent=1) + ";\n")
print(len(apps), "apps ->", out)
for a in apps: print(" ", a["name"], a["icon"])
